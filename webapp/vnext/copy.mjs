export function applicationLocale() { return globalThis.document?.documentElement?.lang === "en" ? "en" : "ru"; }
export function localeOf(model) { return model?.locale === "en" || model?.locale === "ru" ? model.locale : applicationLocale(); }
export function escapeCopy(value) { return String(value ?? "").replace(/[&<>"']/g, ch => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[ch])); }

export function copy(key, locale = applicationLocale(), params = {}) {
  const value = Object.hasOwn(COPY, key) ? COPY[key] : null;
  if (!value) {
    console.warn(`Unknown copy key: ${key}`);
    return key;
  }
  return value[locale === "en" ? "en" : "ru"].replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

