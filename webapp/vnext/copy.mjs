export function unknownVerdictSubtitle(model) {
  const check = model.check;
  if (model.checkStartFailed || model.executionStatus === "failed" || check?.execution_status !== "completed" || check.is_current === false || check.verdict !== "unknown") return "";
  // Use server reasons only. Redundant projection of the same missing field is one reason.
  const reasons = [...(check.blocking_issues || []), ...(check.missing_fields || []), ...(check.evidence_summary?.missing_fields || [])];
  const blockingCodes = (check.blocking_issues || []).map(item => item.code || item.reason_code || "");
  const missingProjection = { pcd_unknown: "pcd", center_bore_unknown: "center_bore", offset_unknown: "offset_et", rim_offset_missing: "offset_et", vehicle_reference_offset_missing: "vehicle_reference_offset", size_not_in_reference: "provider_allowed_wheels", size_unknown: "diameter_width", vehicle_not_resolved: "vehicle_identity" };
  const projected = new Set(blockingCodes.map(code => missingProjection[code]).filter(Boolean));
  const codes = [...new Set(reasons.map(item => typeof item === "string" ? item : item.code || item.reason_code || ""))].filter(code => !projected.has(code));
  const suffix = codes.length === 1 && Object.hasOwn(unknownReasonKeys, codes[0]) ? unknownReasonKeys[codes[0]] : null;
  const fallback = copy("fitment.verdict.unknown.fallback", model.locale);
  const subtitle = suffix ? copy(`fitment.verdict.unknown.${suffix}`, model.locale) : fallback;
  const labels = [...(model.blockingIssues || []), ...(model.missingData || []), ...reasons].map(item => typeof item === "string" ? item : item.label || item.message || "");
  return labels.some(label => label.trim() === subtitle) ? fallback : subtitle;
}

