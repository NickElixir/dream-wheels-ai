export function errorCopy(error, locale = applicationLocale()) {
  if (typeof error?.safe_text === "string") return error.safe_text;
  const code = typeof error === "string" ? error : error?.code || error?.error_code;
  return copy(Object.hasOwn(errorKeys, code) ? errorKeys[code] : "errors.generic", locale);
}

// Compatibility adapter for legacy keyed DOM and runtime presentation formatters.
// All text remains owned by COPY; this contains no independent translations.
export function legacyTranslations() {
  const dictionaries = { ru: {}, en: {} };
  for (const [key, pair] of Object.entries(COPY)) {
    if (!key.startsWith("legacy.")) continue;
    const parts = key.slice(7).split(".");
    const name = parts.pop();
    for (const locale of ["ru", "en"]) {
      let target = dictionaries[locale];
      for (const part of parts) target = target[part] ||= {};
      target[name] = pair[locale];
    }
  }
  for (const path of ["wallet.stepChooseSub","wallet.confirmHint","wallet.securePaymentTitle","wallet.securePaymentText","wallet.paymentHistoryHint","wallet.topUpHistoryHint","renders.lede"]) {
    const parts = path.split("."); const name = parts.pop();
    for (const locale of ["ru", "en"]) {
      let target = dictionaries[locale];
      for (const part of parts) target = target[part] ||= {};
      target[name] = "";
    }
  }
  return dictionaries;
}
