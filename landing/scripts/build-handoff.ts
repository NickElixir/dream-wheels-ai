import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { showcaseVariants, getWheel, getWheelSku } from '../src/data/catalog';
import overrides from '../src/data/catalog-primary-skus.json';
import registry from '../src/data/catalog-asset-registry.json';
import storage from '../src/data/catalog-storage.json';
import publications from '../src/data/catalog-publications.json';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args=process.argv.slice(2);
const targetIndex=args.indexOf('--target');
const target=targetIndex<0?'production':args[targetIndex+1];
if(target!=='production'&&target!=='staging')throw Error('Target must be production or staging');
const primary = overrides as Record<string, string>;
for (const key of Object.keys(primary)) if (!showcaseVariants.some(v => v.id === key)) throw Error(`Unknown pair: ${key}`);
const entries = showcaseVariants.map(variant => {
  const wheel = getWheel(variant.wheelId)!;
  const asset=registry.assets.find(item=>item.barcode===wheel.referenceBarcode);
  if(!asset)throw Error(`Unmapped image: ${wheel.id}`);
  const selectedSkuId = primary[variant.id] ?? (variant.skuIds.length === 1 ? variant.skuIds[0] : null);
  if (selectedSkuId && !variant.skuIds.includes(selectedSkuId)) throw Error(`Invalid primary SKU: ${variant.id}`);
  return { variantId: variant.id, vehicleId: variant.vehicleId, designId: wheel.id,
    name: wheel.displayName, brand: wheel.brand, model: wheel.model, assetId:asset.id, selectedSkuId,
    skus: variant.skuIds.map(id => getWheelSku(id)!) };
});
fs.writeFileSync(path.join(root,'webapp/vnext/catalog-assets.mjs'),`// Generated by landing/scripts/build-handoff.ts; no credentials.\nexport const catalogAssetRegistry = ${JSON.stringify(registry,null,2)};\nexport const catalogStorageTarget = ${JSON.stringify(storage.targets[target])};\nexport const catalogBucket = ${JSON.stringify(storage.bucket)};\nexport const catalogPublication = ${JSON.stringify(publications[target])};\n`);
fs.writeFileSync(path.join(root, 'webapp/vnext/catalog-data.mjs'), `// Generated by landing/scripts/build-handoff.ts; do not edit.\nexport const catalogEntries = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`${entries.length} pairs; ${entries.filter(x => !x.selectedSkuId).length} require a primary SKU decision; Storage target: ${target}`);
